import assert from 'node:assert/strict';
const saved={};
const elements=new Map();
const element=id=>{if(!elements.has(id))elements.set(id,{value:'',textContent:'',replaceChildren(){},append(){}});return elements.get(id);};
globalThis.document={getElementById:element,createElement:()=>({append(){}})};
globalThis.chrome={runtime:{async sendMessage(){return {value:{required:false}};}},storage:{local:{async get(keys){if(typeof keys==='string')return {[keys]:saved[keys]};return Object.fromEntries(keys.filter(k=>k in saved).map(k=>[k,saved[k]]));},async set(data){Object.assign(saved,data);}}},downloads:{showDefaultFolder(){}},tabs:{create(){}}};
await import('./options.js');
element('notebook').value='https://notebook.google.com/notebook/test-123';
element('folder').value='https://drive.google.com/drive/folders/prompts-123';
element('apiKey').value='example-test-key';
element('replaceSources').checked=true;
await element('save').onclick();
assert.equal(saved.notebook,element('notebook').value);
assert.equal(saved.replaceSources,true);
assert.equal(saved.folder,element('folder').value);
assert.match(element('status').textContent,/Configurações salvas/);
for(const id of ['notebook','folder','apiKey'])element(id).value='';
await import('./options.js?reload');
assert.equal(element('replaceSources').checked,true);
assert.equal(element('apiKey').value,'example-test-key');
assert.equal(element('notebook').value,saved.notebook);
element('notebook').value='https://example.com/';
await element('save').onclick();
assert.equal(saved.notebook,'https://notebook.google.com/notebook/test-123');
assert.match(element('status').textContent,/link.*notebook/i);
console.log('Configurações: gravação, confirmação visível, restauração ao reabrir e rejeição de destino inválido aprovadas.');
